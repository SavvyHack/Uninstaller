using System.Net;
using System.Text;
using System.Text.Json;
using Reclaim.Core.Leftovers;
using Reclaim.Core.Models;

namespace Reclaim.Core.SystemTools;

public enum ExportFormat { Html, Csv, Json, Text }

public static class ExportService
{
    public static string ExportApps(IEnumerable<InstalledApp> apps, ExportFormat format)
    {
        var list = apps.OrderBy(a => a.Name, StringComparer.OrdinalIgnoreCase).ToList();
        return format switch
        {
            ExportFormat.Json => JsonSerializer.Serialize(list.Select(a => new
            {
                a.Name, a.Publisher, a.Version, InstallDate = a.InstallDate?.ToString("yyyy-MM-dd"), a.SizeBytes, a.InstallLocation,
                Source = a.Source.ToString(), a.UninstallString, a.QuietUninstallString, a.RegistryKeyPath,
            }), new JsonSerializerOptions { WriteIndented = true }),
            ExportFormat.Csv => Csv(list),
            ExportFormat.Text => string.Join(Environment.NewLine, list.Select(a => $"{a.Name}\t{a.Version}\t{a.Publisher}\t{a.InstallDate:yyyy-MM-dd}\t{a.SizeText}")),
            _ => Html("Installed programs", ["Name", "Version", "Publisher", "Installed", "Size", "Type", "Location"],
                list.Select(a => new[] { a.Name, a.Version ?? "", a.Publisher ?? "", a.InstallDate?.ToString("yyyy-MM-dd") ?? "", a.SizeText, a.Source.ToString(), a.InstallLocation ?? "" })),
        };
    }

    public static string ExportLeftovers(string appName, IEnumerable<LeftoverItem> items) =>
        Html($"Leftovers of {appName}", ["Confidence", "Type", "Location", "Size", "Why"],
            items.Select(i => new[] { $"{i.Confidence} ({i.Bucket})", i.Kind.ToString(), i.Display, i.SizeText, i.Reason }));

    private static string Csv(List<InstalledApp> list)
    {
        static string Q(string? s) => "\"" + (s ?? "").Replace("\"", "\"\"") + "\"";
        var sb = new StringBuilder("Name,Version,Publisher,InstallDate,SizeBytes,Source,InstallLocation,UninstallString\r\n");
        foreach (var a in list)
            sb.Append(string.Join(",", Q(a.Name), Q(a.Version), Q(a.Publisher), Q(a.InstallDate?.ToString("yyyy-MM-dd")), a.SizeBytes,
                Q(a.Source.ToString()), Q(a.InstallLocation), Q(a.UninstallString))).Append("\r\n");
        return sb.ToString();
    }

    private static string Html(string title, string[] headers, IEnumerable<string[]> rows)
    {
        var sb = new StringBuilder();
        sb.Append("<!doctype html><html><head><meta charset=\"utf-8\"><title>").Append(WebUtility.HtmlEncode(title)).Append("</title><style>")
          .Append("body{font-family:'Segoe UI',system-ui,sans-serif;margin:32px;color:#1b1b1f;background:#f7f7fa}h1{font-weight:600}")
          .Append("table{border-collapse:collapse;width:100%;background:#fff;border-radius:8px;overflow:hidden;box-shadow:0 1px 3px rgba(0,0,0,.08)}")
          .Append("th,td{padding:8px 12px;text-align:left;font-size:13px;border-bottom:1px solid #eee}th{background:#f0f0f5;font-weight:600}")
          .Append("@media(prefers-color-scheme:dark){body{background:#1c1c20;color:#eee}table{background:#26262b}th{background:#2f2f35}td,th{border-color:#333}}")
          .Append("</style></head><body><h1>").Append(WebUtility.HtmlEncode(title)).Append("</h1><p>Generated by Reclaim on ")
          .Append(DateTime.Now.ToString("f")).Append("</p><table><tr>");
        foreach (var h in headers) sb.Append("<th>").Append(WebUtility.HtmlEncode(h)).Append("</th>");
        sb.Append("</tr>");
        foreach (var r in rows)
        {
            sb.Append("<tr>");
            foreach (var c in r) sb.Append("<td>").Append(WebUtility.HtmlEncode(c)).Append("</td>");
            sb.Append("</tr>");
        }
        sb.Append("</table></body></html>");
        return sb.ToString();
    }
}
