using System.Text;
using Reclaim.Core.Infrastructure;
using Reclaim.Core.Models;

namespace Reclaim.Core.Uninstall;

public enum ScriptKind { PowerShell, Batch }

/// <summary>Turns a selection of apps into a script that removes them unattended on this or another PC.</summary>
public static class ScriptExporter
{
    public static string Generate(IEnumerable<InstalledApp> apps, ScriptKind kind)
    {
        var sb = new StringBuilder();
        if (kind == ScriptKind.PowerShell)
        {
            sb.AppendLine("# Generated by Reclaim Uninstaller on " + DateTime.Now.ToString("yyyy-MM-dd HH:mm"));
            sb.AppendLine("#Requires -RunAsAdministrator");
            sb.AppendLine("$ErrorActionPreference = 'Continue'");
            sb.AppendLine();
        }
        else
        {
            sb.AppendLine("@echo off");
            sb.AppendLine("rem Generated by Reclaim Uninstaller on " + DateTime.Now.ToString("yyyy-MM-dd HH:mm"));
            sb.AppendLine("rem Run from an elevated command prompt.");
            sb.AppendLine();
        }

        foreach (var app in apps)
        {
            var line = Line(app, kind, out var note);
            sb.AppendLine(kind == ScriptKind.PowerShell ? $"# {app.Name} {app.Version}".TrimEnd() : $"rem {app.Name} {app.Version}".TrimEnd());
            if (note is not null) sb.AppendLine((kind == ScriptKind.PowerShell ? "# " : "rem ") + note);
            if (line is not null) sb.AppendLine(line);
            sb.AppendLine();
        }
        return sb.ToString();
    }

    private static string? Line(InstalledApp app, ScriptKind kind, out string? note)
    {
        note = null;
        var ps = kind == ScriptKind.PowerShell;
        switch (app.Source)
        {
            case AppSource.Store:
                var family = app.Extra.GetValueOrDefault("PackageFamilyName") ?? "";
                var name = family.Contains('_') ? family[..family.LastIndexOf('_')] : family;
                var cmd = $"Get-AppxPackage -Name '{name}' | Remove-AppxPackage";
                return ps ? cmd : $"powershell -NoProfile -Command \"{cmd}\"";
            case AppSource.BrowserExtension or AppSource.Orphan or AppSource.Forced:
                note = "Not scriptable: remove this item from Reclaim.";
                return null;
        }

        var quiet = SilentArgs.Build(app);
        var command = quiet ?? app.UninstallString;
        if (command is null)
        {
            note = "No uninstall command registered.";
            return null;
        }
        if (quiet is null) note = "No silent switch known. This uninstaller will show its own window.";

        var (exe, args) = CommandLine.Split(command);
        if (!ps) return $"start \"\" /wait {CommandLine.Quote(exe)} {args}".TrimEnd();
        var argPart = string.IsNullOrWhiteSpace(args) ? "" : $" -ArgumentList '{args.Replace("'", "''")}'";
        return $"Start-Process -FilePath '{exe.Trim('"').Replace("'", "''")}'{argPart} -Wait";
    }
}
